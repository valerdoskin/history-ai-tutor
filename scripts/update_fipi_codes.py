def normalize(s: str) -> str:
    """Нормализация для сравнения: нижний регистр, сжатие пробелов, удаление кавычек."""
    s = re.sub(r"[«»\"'„“”]", "", s)
    return re.sub(r"\s+", " ", s.strip().lower())


def find_codes(book_id: str, chapter_title: str, paragraph_title: str):
    """Возвращает список кодов для параграфа или None, если не найден."""
    rules = MAPPING.get((book_id, chapter_title))
    if not rules:
        return None
    p = normalize(paragraph_title)
    for substr, codes in rules:
        if substr.lower() in p:
            return codes
    return None


def main() -> None:
    with open(ENRICHED, encoding="utf-8") as fh:
        enriched = json.load(fh)

    matched = 0
    unmatched = 0
    unmatched_paras = []
    for key, para in enriched.items():
        if not isinstance(para, dict):
            continue
        md = para.get("metadata")
        if not isinstance(md, dict):
            continue
        book_id = para.get("book_id")
        chapter_title = para.get("chapter_title")
        paragraph_title = para.get("paragraph_title")
        codes = find_codes(book_id, chapter_title, paragraph_title)
        if codes is not None:
            md["fipi_codes"] = codes
            matched += 1
        else:
            unmatched += 1
            unmatched_paras.append((book_id, chapter_title, paragraph_title))

    with open(ENRICHED, "w", encoding="utf-8") as fh:
        json.dump(enriched, fh, ensure_ascii=False, indent=2)

    print(f"Параграфов с сопоставленными кодами: {matched}")
    print(f"Параграфов без сопоставления: {unmatched}")
    if unmatched_paras:
        print("Несопоставленные параграфы:")
        for book, chap, para in unmatched_paras:
            print(f"  [{book}] [{chap}] :: {para}")


if __name__ == "__main__":
    main()
